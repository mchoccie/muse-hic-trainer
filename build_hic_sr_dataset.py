#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Build Hi-C paired datasets with downsampled counts (same resolution).
- Both HR and LR tiles: 512x512 @ 25 kb
- LR generated by stochastic downsampling of counts
- Outputs:
    highdepth_dataset.npy   (N,1,512,512)   ground truth
    lowdepth_dataset.npy    (N,1,512,512)   downsampled version
    highdepth_mask.npy      (N,1,512,512)
    lowdepth_mask.npy       (N,1,512,512)
    hic_window_coords.npy   (N,) object of (chrom, start_bp, end_bp)
"""

import os
import argparse
import numpy as np
import cooler

# ---------- helpers ----------
def distance_map(n: int) -> np.ndarray:
    i = np.arange(n, dtype=np.float32)
    d = np.abs(i[:, None] - i[None, :])
    return d / max(1.0, d.max())

def preprocess_counts_tile(x: np.ndarray, pclip: float) -> np.ndarray:
    """log1p -> clip percentiles -> scale [0,1]."""
    x = np.log1p(np.clip(x, 0, None)).astype(np.float32)
    lo, hi = np.percentile(x, [100 - pclip, pclip])
    if hi <= lo:
        lo, hi = x.min(), x.max()
        if hi <= lo:
            hi = lo + 1.0
    x = np.clip(x, lo, hi)
    return (x - lo) / max(hi - lo, 1e-6)

def preprocess_counts_batch(X: np.ndarray, pclip: float) -> np.ndarray:
    return np.stack([preprocess_counts_tile(x, pclip) for x in X]).astype(np.float32)

# --- NEW: shared-scale normalization so LR doesn't get re-stretched to look like HR ---
def preprocess_counts_tile_pair(hr: np.ndarray, lr: np.ndarray, pclip: float) -> tuple[np.ndarray, np.ndarray]:  # <<< CHANGED
    """log1p both; compute percentiles from HR ONLY; apply same scale to HR & LR; min-max -> [0,1]."""         # <<< CHANGED
    hr_lp = np.log1p(np.clip(hr, 0, None)).astype(np.float32)                                                  # <<< CHANGED
    lr_lp = np.log1p(np.clip(lr, 0, None)).astype(np.float32)                                                  # <<< CHANGED
    lo, hi = np.percentile(hr_lp, [100 - pclip, pclip])                                                         # <<< CHANGED
    if hi <= lo:                                                                                                # <<< CHANGED
        lo, hi = float(hr_lp.min()), float(hr_lp.max())                                                         # <<< CHANGED
        if hi <= lo:                                                                                            # <<< CHANGED
            hi = lo + 1.0                                                                                       # <<< CHANGED
    hr_lp = np.clip(hr_lp, lo, hi); lr_lp = np.clip(lr_lp, lo, hi)                                              # <<< CHANGED
    denom = max(hi - lo, 1e-6)                                                                                  # <<< CHANGED
    return ((hr_lp - lo) / denom).astype(np.float32), ((lr_lp - lo) / denom).astype(np.float32)                 # <<< CHANGED

def preprocess_counts_batch_shared(HR: np.ndarray, LR: np.ndarray, pclip: float) -> tuple[np.ndarray, np.ndarray]:  # <<< CHANGED
    assert HR.shape == LR.shape                                                                                     # <<< CHANGED
    out_hr, out_lr = [], []                                                                                         # <<< CHANGED
    for i in range(HR.shape[0]):                                                                                    # <<< CHANGED
        h, l = preprocess_counts_tile_pair(HR[i], LR[i], pclip)                                                     # <<< CHANGED
        out_hr.append(h); out_lr.append(l)                                                                          # <<< CHANGED
    return np.stack(out_hr).astype(np.float32), np.stack(out_lr).astype(np.float32)                                 # <<< CHANGED

# --- REPLACED: true HiCPlus-style thinning on *integer* raw counts  ---
def downsample_counts(M: np.ndarray, frac: float, rng: np.random.Generator) -> np.ndarray:  # <<< CHANGED
    """Binomial thinning of *integer* counts (HiCPlus genDownsample equivalent)."""          # <<< CHANGED
    if frac <= 0:
        return np.zeros_like(M, dtype=np.float32)                                            # <<< CHANGED
    if frac >= 1:
        return np.clip(M, 0, None).astype(np.float32)                                        # <<< CHANGED
    M_int = np.clip(M, 0, None).astype(np.int64, copy=False)                                 # <<< CHANGED
    return rng.binomial(M_int, frac).astype(np.float32)                                      # <<< CHANGED

# ---------- extraction ----------
def extract_hr_windows(data_folder, highres_res, high_bins, stride_bins,
                       min_valid_frac, skip_chrY, balanced=False):   # default -> UNBALANCED RAW  # <<< CHANGED
    hi_tiles, hi_masks, coords = [], [], []
    mcools = [f for f in sorted(os.listdir(data_folder)) if f.endswith(".mcool")]
    if not mcools:
        raise FileNotFoundError(f"No .mcool files in {data_folder}")

    for fname in mcools:
        path = os.path.join(data_folder, f"{fname}::resolutions/{highres_res}")
        print(f"\n>>> {fname} @ {highres_res}")
        clr = cooler.Cooler(path)

        for chrom in clr.chromnames:
            if skip_chrY and chrom.lower().endswith("y"):
                continue

            # IMPORTANT: unbalanced raw counts so thinning operates on integers
            M = clr.matrix(balance=balanced).fetch(chrom).astype(np.float32)   # <<< CHANGED (balanced default False)
            mask = np.isfinite(M).astype(np.float32)
            M = np.nan_to_num(M, nan=0.0)

            kept = 0
            for j in range(0, M.shape[0] - high_bins + 1, stride_bins):
                start_bp = j * highres_res
                end_bp   = start_bp + high_bins * highres_res
                H  = M[j:j+high_bins, j:j+high_bins]
                Hm = mask[j:j+high_bins, j:j+high_bins]

                if Hm.mean() < min_valid_frac:
                    continue

                hi_tiles.append(H)
                hi_masks.append(Hm)
                coords.append((chrom, int(start_bp), int(end_bp)))
                kept += 1
            print(f"  {chrom}: kept {kept} windows")

    hi_tiles = np.stack(hi_tiles).astype(np.float32)
    hi_masks = np.stack(hi_masks).astype(np.float32)
    coords   = np.array(coords, dtype=object)
    print("\n--- extracted ---")
    print("hi_tiles:", hi_tiles.shape)
    return hi_tiles, hi_masks, coords

# ---------- main ----------
def main():
    ap = argparse.ArgumentParser(description="Build Hi-C dataset with downsampled reads")
    ap.add_argument("--data-folder", type=str, required=True)
    ap.add_argument("--highres-res", type=int, default=25_000)
    ap.add_argument("--high-bins", type=int, default=512)
    ap.add_argument("--stride-bins", type=int, default=256)
    ap.add_argument("--min-valid-frac", type=float, default=0.70)
    ap.add_argument("--skip-chrY", action="store_true", default=True)
    ap.add_argument("--no-balance", action="store_true")
    ap.add_argument("--pclip", type=float, default=99.5)
    ap.add_argument("--downsample-frac", type=float, default=0.25,
                    help="Fraction of reads kept for low-depth (e.g., 0.25=25%)")
    ap.add_argument("--out-prefix", type=str, default="")
    args = ap.parse_args()

    # Force UNBALANCED for proper integer thinning regardless of --no-balance flag:
    hi_counts, hi_mask, coords = extract_hr_windows(                                  # <<< CHANGED
        data_folder=args.data_folder,
        highres_res=args.highres_res,
        high_bins=args.high_bins,
        stride_bins=args.stride_bins,
        min_valid_frac=args.min_valid_frac,
        skip_chrY=args.skip_chrY,
        balanced=False,  # ALWAYS raw counts for downsampling (ignores --no-balance)  # <<< CHANGED
    )
    N = hi_counts.shape[0]

    rng = np.random.default_rng(42)

    # Low-depth via stochastic thinning (HiCPlus-equivalent)
    lo_counts = np.stack([downsample_counts(hi_counts[i], args.downsample_frac, rng)
                          for i in range(N)]).astype(np.float32)
    lo_mask = hi_mask.copy()  # masks unchanged

    print("\n--- downsampled -> LR ---")
    print("lo_counts:", lo_counts.shape)

    # Preprocess both with **shared HR scale** (preserve LR contrast)
    # (replaces independent per-tile preprocessing)
    hi_img, lo_img = preprocess_counts_batch_shared(hi_counts, lo_counts, args.pclip)  # <<< CHANGED

    # Package (channel dim)
    highres_img  = hi_img[:, None]
    highres_mask = hi_mask[:, None]
    lowres_img   = lo_img[:, None]
    lowres_mask  = lo_mask[:, None]

    # Save
    def _name(x): return f"{args.out_prefix}{x}" if args.out_prefix else x
    np.save(_name("highdepth_dataset.npy"), highres_img)
    np.save(_name("highdepth_mask.npy"),    highres_mask)
    np.save(_name("lowdepth_dataset.npy"),  lowres_img)
    np.save(_name("lowdepth_mask.npy"),     lowres_mask)
    np.save(_name("hic_window_coords.npy"), coords)

    print("\n--- final tensors ---")
    print("highdepth_dataset:", highres_img.shape)
    print("lowdepth_dataset :", lowres_img.shape)
    print(f"Saved {N} datapoints ✓")

if __name__ == "__main__":
    main()
